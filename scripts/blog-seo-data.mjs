export function blogImageKey(image = {}) {
  return String(image.assetKey || image.src || "").trim();
}

export function blogSeoDataForSlug(slug) {
  return BLOG_SEO_RECORDS[String(slug || "").trim()] || null;
}

export function completeBlogSeoData(post, { requirePublishedImage = true } = {}) {
  const editorial = blogSeoDataForSlug(post?.slug);
  if (!editorial) throw new Error(`BLOG_SEO_RECORD_MISSING:${post?.slug || "unknown"}`);
  const blocks = (post.blocks || []).map((block) => {
    if (block.type !== "image") return block;
    const key = blogImageKey(block);
    const dimensions = BLOG_IMAGE_DIMENSIONS[key];
    if (!dimensions) throw new Error(`BLOG_IMAGE_DIMENSIONS_MISSING:${post.slug}:${key || "unknown"}`);
    return { ...block, width: dimensions.width, height: dimensions.height };
  });
  const featuredBlock = editorial.featuredImageKey
    ? blocks.find((block) => block.type === "image" && blogImageKey(block) === editorial.featuredImageKey)
    : null;
  if (requirePublishedImage && post.status === "published" && !featuredBlock) {
    throw new Error(`BLOG_FEATURED_IMAGE_MISSING:${post.slug}`);
  }
  const featuredImage = featuredBlock
    ? {
        ...(featuredBlock.storageId ? { storageId: featuredBlock.storageId } : {}),
        ...(featuredBlock.assetKey ? { assetKey: featuredBlock.assetKey } : {}),
        ...(!featuredBlock.storageId && !featuredBlock.assetKey && featuredBlock.src ? { src: featuredBlock.src } : {}),
        alt: String(featuredBlock.alt || featuredBlock.text || "Article image").trim(),
        width: featuredBlock.width,
        height: featuredBlock.height,
      }
    : undefined;
  return {
    ...post,
    seoTitle: editorial.seoTitle,
    seoDescription: editorial.seoDescription,
    language: editorial.language,
    author: editorial.author,
    articleSection: editorial.articleSection,
    ...(featuredImage ? { featuredImage } : {}),
    blocks,
  };
}
